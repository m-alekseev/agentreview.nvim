local highlight = require("agentreview.highlight")

describe("highlight.word_ranges", function()
  it("marks inserted text only on the new line", function()
    local old, new, similarity = highlight.word_ranges("local y = compute(x)", 'local y = compute(x, "opts")')
    assert.same({}, old)
    assert.same({ { 19, 27 } }, new)
    assert.is_true(similarity >= 0.5)
  end)

  it("marks a swapped value on both lines", function()
    local old, new = highlight.word_ranges("retries = 3", "retries = 5")
    assert.same({ { 10, 11 } }, old)
    assert.same({ { 10, 11 } }, new)
  end)

  it("merges adjacent changed tokens into one range", function()
    local old, new = highlight.word_ranges("a b", "a (c)")
    assert.same({ { 2, 3 } }, old)
    assert.same({ { 2, 5 } }, new)
  end)

  it("keeps unchanged words between two changes separate", function()
    local old, new = highlight.word_ranges("a foo bar b", "a baz qux b")
    assert.same({ { 2, 5 }, { 6, 9 } }, old)
    assert.same({ { 2, 5 }, { 6, 9 } }, new)
  end)

  it("reports low similarity for unrelated lines", function()
    local _, _, similarity = highlight.word_ranges("-- legacy retry count", "local z = y * 2")
    assert.is_true(similarity < 0.5)
  end)

  it("handles multibyte words", function()
    local old, new = highlight.word_ranges("x = привет", "x = мир")
    assert.same({ { 4, 16 } }, old)
    assert.same({ { 4, 10 } }, new)
  end)
end)
